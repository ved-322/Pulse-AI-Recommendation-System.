-- ============================================================
--  AI-Based Recommendation System : relational schema (H2 / JDBC)
-- ============================================================

CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(80)  NOT NULL,
  email         VARCHAR(120) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role          VARCHAR(10)  NOT NULL DEFAULT 'USER' CHECK (role IN ('ADMIN','USER')),
  active        BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categories (
  name  VARCHAR(40) PRIMARY KEY,
  emoji VARCHAR(8)  NOT NULL,
  color VARCHAR(9)  NOT NULL
);

CREATE TABLE IF NOT EXISTS items (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug        VARCHAR(160) NOT NULL UNIQUE,
  name        VARCHAR(140) NOT NULL,
  brand       VARCHAR(80)  NOT NULL,
  category    VARCHAR(40)  NOT NULL,
  description VARCHAR(500) NOT NULL,
  price       DECIMAL(12,2) NOT NULL CHECK (price >= 0),
  tags        VARCHAR(200) NOT NULL,
  meta        VARCHAR(20)  NOT NULL DEFAULT '',
  emoji       VARCHAR(8)   NOT NULL,
  accent      VARCHAR(9)   NOT NULL,
  FOREIGN KEY (category) REFERENCES categories(name)
);

CREATE TABLE IF NOT EXISTS reviews (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT       NOT NULL,
  item_id    BIGINT       NOT NULL,
  rating     INT          NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body       VARCHAR(1000) NOT NULL,
  sample     BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (user_id, item_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (item_id) REFERENCES items(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_preferences (
  user_id  BIGINT      NOT NULL,
  category VARCHAR(40) NOT NULL,
  weight   INT         NOT NULL CHECK (weight BETWEEN 0 AND 5),
  PRIMARY KEY (user_id, category),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_tags (
  user_id BIGINT      NOT NULL,
  tag     VARCHAR(40) NOT NULL,
  PRIMARY KEY (user_id, tag),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS interactions (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT      NOT NULL,
  item_id    BIGINT      NOT NULL,
  type       VARCHAR(10) NOT NULL CHECK (type IN ('VIEW','CLICK','LIKE','PURCHASE','DISMISS')),
  created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (item_id) REFERENCES items(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS recommendation_log (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT      NOT NULL,
  item_id    BIGINT      NOT NULL,
  score      DOUBLE      NOT NULL,
  source     VARCHAR(20) NOT NULL,
  outcome    VARCHAR(10) NOT NULL DEFAULT 'SHOWN' CHECK (outcome IN ('SHOWN','CLICK','LIKE','PURCHASE','DISMISSED')),
  shown_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  outcome_at TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (item_id) REFERENCES items(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS settings (
  setting_key   VARCHAR(50)  PRIMARY KEY,
  setting_value VARCHAR(100) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_reviews_item ON reviews(item_id);
CREATE INDEX IF NOT EXISTS idx_interactions_user ON interactions(user_id);
CREATE INDEX IF NOT EXISTS idx_interactions_item ON interactions(item_id);
CREATE INDEX IF NOT EXISTS idx_reclog_user_item  ON recommendation_log(user_id, item_id);
CREATE INDEX IF NOT EXISTS idx_reclog_shown      ON recommendation_log(shown_at);
